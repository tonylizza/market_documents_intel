import type { PassageSearchParams } from "@/lib/domain/passage";
import type { RelevanceGrade } from "./metrics";

export type EvaluationCategory =
  | "direct_keyword"
  | "phrase"
  | "semantic_paraphrase"
  | "company_specific"
  | "report_period_specific"
  | "comparison_status"
  | "risk_category"
  | "lexical_favored"
  | "semantic_favored"
  | "ambiguous"
  | "weak_match"
  | "no_answer"
  | "repeated_passage"
  | "filter_sensitive"
  /** Milestone 7B.1a: a real, genuine short (16-30 word) passage of real
   * prose -- included so remediation strategies are graded on whether they
   * *preserve* useful short passages, not just suppress fragments. */
  | "short_substantive_passage"
  /** Milestone 7B.1a: a query specifically chosen because a known
   * heading-only/generic-heading fragment (e.g. "BACK", "Operations
   * (continued)") is a plausible high-similarity false positive for it --
   * the adversarial counterpart to `short_substantive_passage`. */
  | "short_fragment_trap";

/** Whether relevance for a case is judged against the passage id (any
 * context of that passage counts) or a specific retrieval-context id (the
 * comparison/side matters, e.g. a `comparison_status` case). */
export type RelevanceLevel = "passage" | "context";

/** What ranking behavior is expected for this query -- used to report
 * semantic-paraphrase/lexical-favored metrics as named groups rather than
 * inferring intent from `category` alone. */
export type ExpectedBehavior = "lexical_favored" | "semantic_favored" | "either" | "no_answer";

export interface RetrievalEvaluationCase {
  id: string;
  category: EvaluationCategory;
  query: string;
  exactPhrase?: boolean;
  filters?: Partial<PassageSearchParams>;
  /** Corpus-derived, human-reviewed (by the implementer, reading real
   * passage text against the live corpus) relevant passage ids -- never
   * generated by the embedding model under test. Empty for `no_answer`
   * cases (there is deliberately no relevant passage). */
  relevantPassageIds: string[];
  /** Retrieval-context ids, when relevance genuinely depends on which
   * comparison/side a passage occupies (e.g. `comparison_status`,
   * `repeated_passage`) -- optional; most cases judge at the passage level. */
  relevantContextIds?: string[];
  relevanceLevel: RelevanceLevel;
  gradedRelevance?: Record<string, RelevanceGrade>;
  expectNoAnswer?: boolean;
  expectedBehavior: ExpectedBehavior;
  /** For `comparison_status`/`filter_sensitive`/`company_specific`/
   * `report_period_specific` cases: every returned result must satisfy
   * this predicate description -- checked at runtime by the evaluation
   * runner against each result's actual company/period/status. */
  expectedCompanyTicker?: string;
  expectedAlignmentStatus?: string;
  expectedReportSide?: "EARLIER" | "LATER";
  /** Known passage ids that are plausible short-fragment/generic-heading
   * false positives for this specific query -- used to compute the
   * top-5/top-10 irrelevant-short-fragment rate per case. */
  knownShortFragmentTraps?: string[];
  notes: string;
}

