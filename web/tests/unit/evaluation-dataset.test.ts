import { describe, expect, it } from "vitest";
import { RETRIEVAL_EVALUATION_DATASET, type EvaluationCategory } from "@/evaluation/dataset";

const REQUIRED_CATEGORIES: EvaluationCategory[] = [
  "direct_keyword",
  "phrase",
  "semantic_paraphrase",
  "company_specific",
  "report_period_specific",
  "comparison_status",
  "risk_category",
  "lexical_favored",
  "semantic_favored",
  "ambiguous",
  "weak_match",
  "no_answer",
  "repeated_passage",
  "filter_sensitive",
  "short_substantive_passage",
  "short_fragment_trap",
];

describe("RETRIEVAL_EVALUATION_DATASET", () => {
  it("has at least 75 cases (Milestone 7B.1a expansion)", () => {
    expect(RETRIEVAL_EVALUATION_DATASET.length).toBeGreaterThanOrEqual(75);
  });

  it("has at least 10 no_answer and 10 weak_match cases", () => {
    const noAnswer = RETRIEVAL_EVALUATION_DATASET.filter((c) => c.category === "no_answer");
    const weakMatch = RETRIEVAL_EVALUATION_DATASET.filter((c) => c.category === "weak_match");
    expect(noAnswer.length).toBeGreaterThanOrEqual(10);
    expect(weakMatch.length).toBeGreaterThanOrEqual(10);
  });

  it("every case declares relevanceLevel and expectedBehavior", () => {
    for (const c of RETRIEVAL_EVALUATION_DATASET) {
      expect(["passage", "context"], c.id).toContain(c.relevanceLevel);
      expect(["lexical_favored", "semantic_favored", "either", "no_answer"], c.id).toContain(c.expectedBehavior);
    }
  });

  it("short_fragment_trap cases document at least one known trap or rely on the corpus-wide repeated-heading check", () => {
    const trapCases = RETRIEVAL_EVALUATION_DATASET.filter((c) => c.category === "short_fragment_trap");
    expect(trapCases.length).toBeGreaterThanOrEqual(3);
  });

  it("short_substantive_passage cases have a real relevant passage id each", () => {
    const cases = RETRIEVAL_EVALUATION_DATASET.filter((c) => c.category === "short_substantive_passage");
    expect(cases.length).toBeGreaterThanOrEqual(2);
    for (const c of cases) {
      expect(c.relevantPassageIds.length, c.id).toBeGreaterThan(0);
    }
  });

  it("has unique case ids", () => {
    const ids = RETRIEVAL_EVALUATION_DATASET.map((c) => c.id);
    expect(new Set(ids).size).toBe(ids.length);
  });

  it("covers every required evaluation category", () => {
    const present = new Set(RETRIEVAL_EVALUATION_DATASET.map((c) => c.category));
    for (const category of REQUIRED_CATEGORIES) {
      expect(present.has(category), `missing category: ${category}`).toBe(true);
    }
  });

  it("every case has a non-empty query and a documented rationale", () => {
    for (const c of RETRIEVAL_EVALUATION_DATASET) {
      expect(c.query.trim().length, c.id).toBeGreaterThan(0);
      expect(c.notes.trim().length, c.id).toBeGreaterThan(0);
    }
  });

  it("no_answer cases expect no answer and have no relevant passages", () => {
    const noAnswerCases = RETRIEVAL_EVALUATION_DATASET.filter((c) => c.category === "no_answer");
    expect(noAnswerCases.length).toBeGreaterThan(0);
    for (const c of noAnswerCases) {
      expect(c.expectNoAnswer).toBe(true);
      expect(c.relevantPassageIds).toEqual([]);
    }
  });

  it("comparison_status cases declare the expected alignment status", () => {
    const statusCases = RETRIEVAL_EVALUATION_DATASET.filter((c) => c.category === "comparison_status");
    for (const c of statusCases) {
      expect(c.expectedAlignmentStatus, c.id).toBeTruthy();
      expect(c.filters?.alignmentStatus, c.id).toBe(c.expectedAlignmentStatus);
    }
  });

  it("company_specific cases declare the expected company ticker consistent with filters", () => {
    const companyCases = RETRIEVAL_EVALUATION_DATASET.filter((c) => c.category === "company_specific");
    for (const c of companyCases) {
      if (c.expectedCompanyTicker) {
        expect(c.filters?.company).toBe(c.expectedCompanyTicker);
      }
    }
  });

  it("repeated_passage cases reference a real single passage id each", () => {
    const repeatedCases = RETRIEVAL_EVALUATION_DATASET.filter((c) => c.category === "repeated_passage");
    expect(repeatedCases.length).toBeGreaterThanOrEqual(3);
    for (const c of repeatedCases) {
      expect(c.relevantPassageIds.length, c.id).toBe(1);
    }
  });

  it("filter_sensitive cases exist in pairs/groups that vary only the filter, not the query semantics", () => {
    const filterCases = RETRIEVAL_EVALUATION_DATASET.filter((c) => c.category === "filter_sensitive");
    expect(filterCases.length).toBeGreaterThanOrEqual(2);
    const companyPair = filterCases.filter((c) => c.query === "risk");
    expect(companyPair.length).toBeGreaterThanOrEqual(2);
    const companies = new Set(companyPair.map((c) => c.filters?.company));
    expect(companies.size).toBeGreaterThanOrEqual(2);
  });

  it("relevance judgments were not generated by the model under test (no similarity-derived fields on cases)", () => {
    for (const c of RETRIEVAL_EVALUATION_DATASET) {
      expect(c).not.toHaveProperty("semanticSimilarity");
      expect(c).not.toHaveProperty("embeddingScore");
    }
  });
});
